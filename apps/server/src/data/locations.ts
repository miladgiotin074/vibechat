export interface City {
  id: number;
  name: string;
  provinceId: number;
}
export interface Province {
  id: number;
  name: string;
  cities: City[];
}

export const PROVINCES: Province[] = RAW.map(([id, name, cities]) => ({
  id,
  name,
  cities: cities.map((c, i) => ({ id: id * 100 + i + 1, name: c, provinceId: id })),
}));

const provinceById = new Map(PROVINCES.map((p) => [p.id, p]));
const cityById = new Map(PROVINCES.flatMap((p) => p.cities.map((c) => [c.id, c] as const)));

export const provinceName = (id: number | null | undefined) => (id ? provinceById.get(id)?.name ?? null : null);
export const cityName = (id: number | null | undefined) => (id ? cityById.get(id)?.name ?? null : null);
export const cityInProvince = (cityId: number, provinceId: number) => cityById.get(cityId)?.provinceId === provinceId;
export const isProvince = (id: number) => provinceById.has(id);
